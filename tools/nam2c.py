#!/usr/bin/env python3
"""Extract an A2-Lite model from a .nam file for nam/a2lite.c.

  nam2c.py MODEL.nam --header OUT.h [--name NAME]     C header: weights in .nam stream order
  nam2c.py MODEL.nam --bin OUT.f32                    raw little-endian float32 weights

A plain WaveNet A2-Lite file is taken as is; from an A2 SlimmableContainer the submodel with
3 channels (the Lite width) is used. The shape is checked against the A2 signature.
"""
import argparse
import json
import struct
from pathlib import Path

KS = [6] * 14 + [15, 15] + [6] * 7
DIL = [1, 3, 7, 17, 41, 101, 239] * 2 + [1, 13] + [1, 3, 7, 17, 41, 101, 239]


def pick_lite(doc):
    if doc.get("architecture") == "SlimmableContainer":
        for sub in doc["config"]["submodels"]:
            m = sub["model"]
            if m.get("architecture") == "WaveNet" and m["config"]["layers"][0].get("channels") == 3:
                return m
        raise SystemExit("no 3-channel (A2-Lite) submodel in this container")
    return doc


def check(m):
    if m.get("architecture") != "WaveNet":
        raise SystemExit(f"architecture {m.get('architecture')!r}: only A2 WaveNet models are supported")
    la = m["config"]["layers"]
    if len(la) != 1:
        raise SystemExit("A2 has one layer array")
    L = la[0]
    if L.get("channels") != 3 or L.get("bottleneck") != 3:
        raise SystemExit(f"channels {L.get('channels')}: the pedal runs A2-Lite (3 channels)")
    if L.get("kernel_sizes") != KS or L.get("dilations") != DIL:
        raise SystemExit("kernel sizes / dilations differ from A2")
    if len(m["weights"]) != 1871:
        raise SystemExit(f"{len(m['weights'])} weights, A2-Lite has 1871")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("model", type=Path)
    ap.add_argument("--header", type=Path)
    ap.add_argument("--bin", type=Path)
    ap.add_argument("--name", default="NAM_MODEL")
    a = ap.parse_args()
    m = pick_lite(json.loads(a.model.read_text()))
    check(m)
    w = m["weights"]
    sr = m.get("sample_rate", 48000)
    meta = m.get("metadata", {}) or {}
    loud = meta.get("loudness")
    norm = 10 ** ((-18.0 - float(loud)) / 20.0) if isinstance(loud, (int, float)) else 1.0
    title = "".join(c if 32 <= ord(c) < 127 and c not in '"\\' else "_" for c in a.model.stem)[:22].upper()
    if a.bin:
        a.bin.write_bytes(struct.pack(f"<{len(w)}f", *w))
    if a.header:
        lines = [f"/* generated by tools/nam2c.py from {a.model.name}: A2-Lite, {len(w)} weights, {sr} Hz */",
                 f"#define {a.name}_RATE {int(sr)}u",
                 f"#define {a.name}_NORM {norm:.6g}f   /* loudness {loud} dB -> -18 dB, as the NAM plugin */",
                 f"#define {a.name}_TITLE \"{title}\"",
                 f"static const float {a.name}[{len(w)}] = {{"]
        for i in range(0, len(w), 6):
            lines.append("    " + ", ".join(f"{float(v):.9g}f" for v in w[i:i + 6]) + ",")
        lines.append("};")
        a.header.write_text("\n".join(lines) + "\n")
    print(f"{a.model.name}: A2-Lite, {len(w)} weights, {sr} Hz, loudness {meta.get('loudness')}, "
          f"gain {meta.get('gain')}")


if __name__ == "__main__":
    main()
